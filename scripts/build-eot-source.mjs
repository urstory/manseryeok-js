function series(terms, tau) {
  let s = 0;
  for (const [a, b, c] of terms) s += a * Math.cos(b + c * tau);
  return s;
}
function poly(list, tau) {
  let s = 0;
  let p = 1;
  for (const terms of list) {
    s += series(terms, tau) * p;
    p *= tau;
  }
  return s / 1e8;
}

/** ΔT(초) — Espenak·Meeus (2006) 다항식, y = 소수 해 */
export function deltaT(y) {
  let t;
  if (y < 1600) {
    const u = (y - 1000) / 100;
    return 1574.2 - 556.01 * u + 71.23472 * u ** 2 + 0.319781 * u ** 3 - 0.8503463 * u ** 4 - 0.005050998 * u ** 5 + 0.0083572073 * u ** 6;
  }
  if (y < 1700) {
    t = y - 1600;
    return 120 - 0.9808 * t - 0.01532 * t ** 2 + t ** 3 / 7129;
  }
  if (y < 1800) {
    t = y - 1700;
    return 8.83 + 0.1603 * t - 0.0059285 * t ** 2 + 0.00013336 * t ** 3 - t ** 4 / 1174000;
  }
  if (y < 1860) {
    t = y - 1800;
    return 13.72 - 0.332447 * t + 0.0068612 * t ** 2 + 0.0041116 * t ** 3 - 0.00037436 * t ** 4 + 0.0000121272 * t ** 5 - 0.0000001699 * t ** 6 + 0.000000000875 * t ** 7;
  }
  if (y < 1900) {
    t = y - 1860;
    return 7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3 - 0.0004473624 * t ** 4 + t ** 5 / 233174;
  }
  if (y < 1920) {
    t = y - 1900;
    return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4;
  }
  if (y < 1941) {
    t = y - 1920;
    return 21.2 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3;
  }
  if (y < 1961) {
    t = y - 1950;
    return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547;
  }
  if (y < 1986) {
    t = y - 1975;
    return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718;
  }
  if (y < 2005) {
    t = y - 2000;
    return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5;
  }
  t = y - 2000;
  return 62.92 + 0.32217 * t + 0.005589 * t ** 2;
}

/** 그 순간(JD, UT)의 균시차(초) */
export function equationOfTime(jdUt) {
  const year = 2000 + (jdUt - 2451545) / 365.25;
  const jde = jdUt + deltaT(year) / 86400;
  const tau = (jde - 2451545) / 365250;
  const T = tau * 10;

  // 지심 태양: 지구 일심 좌표를 뒤집는다
  const L = poly([L0, L1, L2, L3, L4, L5], tau);
  const B = poly([B0, B1], tau);
  const R = poly([R0, R1, R2, R3, R4], tau);
  let theta = L + Math.PI;
  let beta = -B;
  // FK5 보정
  const lp = theta - (1.397 * T + 0.00031 * T * T) * D2R;
  theta += -0.09033 * AS2R;
  beta += 0.03916 * (Math.cos(lp) - Math.sin(lp)) * AS2R;

  // 장동(22장 짧은 식)
  const omega = (125.04452 - 1934.136261 * T + 0.0020708 * T * T + (T * T * T) / 450000) * D2R;
  const Ls = (280.4665 + 36000.7698 * T) * D2R;
  const Lm = (218.3165 + 481267.8813 * T) * D2R;
  const dpsi = (-17.2 * Math.sin(omega) - 1.32 * Math.sin(2 * Ls) - 0.23 * Math.sin(2 * Lm) + 0.21 * Math.sin(2 * omega)) * AS2R;
  const deps = (9.2 * Math.cos(omega) + 0.57 * Math.cos(2 * Ls) + 0.1 * Math.cos(2 * Lm) - 0.09 * Math.cos(2 * omega)) * AS2R;
  const eps0 = (23 + 26 / 60 + 21.448 / 3600 - (46.815 * T + 0.00059 * T * T - 0.001813 * T * T * T) / 3600) * D2R;
  const eps = eps0 + deps;

  // 겉보기 황경 → 적경
  const lambda = theta + dpsi - (20.4898 / R) * AS2R;
  const alpha = Math.atan2(Math.sin(lambda) * Math.cos(eps) - Math.tan(beta) * Math.sin(eps), Math.cos(lambda));

  // 식 28.2 평균 경도(도)
  const L0deg = 280.4664567 + 360007.6982779 * tau + 0.03032028 * tau ** 2 + tau ** 3 / 49931 - tau ** 4 / 15300 - tau ** 5 / 2000000;
  let e = L0deg - 0.0057183 - alpha / D2R + (dpsi / D2R) * Math.cos(eps);
  e = ((e % 360) + 540) % 360 - 180;
  return e * 240;
}

/** JD(정수 = 그날 12:00 UT) → 해(율리우스력 1582-10-04까지, 그 뒤 그레고리력) */
export function yearOfJd(jd) {
  let a = jd;
  if (jd >= 2299161) {
    const alpha = Math.floor((jd - 1867216.25) / 36524.25);
    a = jd + 1 + alpha - Math.floor(alpha / 4);
  }
  const b = a + 1524;
  const c = Math.floor((b - 122.1) / 365.25);
  const d = Math.floor(365.25 * c);
  const e = Math.floor((b - d) / 30.6001);
  const month = e < 14 ? e - 1 : e - 13;
  return month > 2 ? c - 4716 : c - 4715;
}

/** 세기마다 파일 하나: [이름, 첫 JD, 끝 JD] */
export function eotFiles() {
  const out = [];
  let start = EOT_FIRST_JD;
  while (start <= EOT_LAST_JD) {
    // 앞뒤로 더 둔 이틀은 이웃 세기 파일에 넣는다
    const cen = (jd) => Math.floor(yearOfJd(Math.min(Math.max(jd, EOT_FIRST_JD + 2), EOT_LAST_JD - 2)) / 100);
    const century = cen(start);
    let end = start;
    while (end + 1 <= EOT_LAST_JD && cen(end + 1) === century) end++;
    out.push([`eot-${century}xx.tsv`, start, end]);
    start = end + 1;
  }
  return out;
}

export const EOT_HEADER = 'jd\teot_sec';

function main() {
  const dir = join(root, 'data/eot');
  mkdirSync(dir, { recursive: true });
  const check = process.argv.includes('--check');
  let bad = 0;
  let n = 0;
  for (const [name, a, b] of eotFiles()) {
    const lines = [EOT_HEADER];
    for (let jd = a; jd <= b; jd++) {
      lines.push(`${jd}\t${equationOfTime(jd).toFixed(2)}`);
      n++;
    }
    const text = lines.join('\n') + '\n';
    const path = join(dir, name);
    if (check) {
      let cur = '';
      try { cur = readFileSync(path, 'utf8').replace(/\r/g, ''); } catch { /* 없음 */ }
      if (cur !== text) {
        console.error(`${name}이 새로 셈한 것과 다르다`);
        bad++;
      }
    } else {
      writeFileSync(path, text);
    }
  }
  if (bad) process.exit(1);
  console.log(check ? `균시차 원본 최신 (${n}일)` : `생성: 균시차 ${n}일`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
