/**
 * 균시차(equation of time) 원본 → data/eot/eot-*.tsv 생성
 *
 * 날마다 12:00 UT의 균시차(초, 소수 둘째 자리)를 Meeus 『Astronomical Algorithms』(2판) 28장 식으로 셈한다.
 *   E = L0 − 0.0057183° − α + Δψ·cos ε
 *   - L0: 태양 평균 경도(식 28.2, τ = 율리우스 천년, 역학시)
 *   - α: 태양 겉보기 적경 — 25장 고정밀법: VSOP87 줄인 급수(부록 III)로 지심 황경·황위·거리,
 *        FK5 보정, 장동(22장, 짧은 식: Δψ 0.5″·Δε 0.1″ 안), 광행차(−20.4898″ / R), 참 황도 경사각
 *   - 역학시 = UT + ΔT (Espenak·Meeus 2006 다항식. ΔT 1분이 균시차에 주는 영향은 0.01초 안팎)
 * 균시차 = 시태양시 − 평균 태양시(해시계가 시계보다 빠르면 +).
 *
 * 라이브러리 안에서는 이 계산을 하지 않는다. 여기서 만든 원본을 scripts/build-eot-table.mjs가 압축해
 * src/data/eot-table.ts로 싣는다. 독립 출처(JPL Horizons) 대조는 scripts/check-eot-horizons.mjs.
 *
 * 범위: JD 2378495(1799-12-30) ~ 2470174(2051-01-02) — 앞뒤 이틀씩 더 둔다(UTC−12~+14 시계와 보간용). 한 세기씩 파일 하나.
 *   1391~1799년은 번들 크기 때문에 싣지 않는다(data/eot/README.md)
 * 쓰는 법: node scripts/build-eot-source.mjs [--check]
 *   --check  파일을 쓰지 않고, 지금 원본이 새로 셈한 것과 같은지만 본다
 */
